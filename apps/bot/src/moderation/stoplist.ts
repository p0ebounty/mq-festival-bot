/**
 * Аварийный список слов — единственный слой, который работает без сети.
 *
 * Нужен ровно для одного случая: классификатор недоступен (27.08 часть
 * эндпоинтов kie.ai отдавала 500 на все модели). Тогда генерация всё
 * равно не идёт, но участнику лучше услышать внятную причину, чем
 * «проверка не отвечает».
 *
 * ⚠️ Список намеренно КОРОТКИЙ и только на очевидное. Расширять его
 * соблазнительно и неправильно: решать должен классификатор, который
 * понимает контекст. Список слов не отличает «мечеть на закате» от
 * «пророк у мечети» и не знает, что Цезарь можно, а современный политик
 * нельзя (ADR 0014).
 *
 * Сюда НЕ добавляются «меч», «битва», «дым», «арена» и прочее из
 * исторических заданий — иначе аварийный слой начнёт резать собственный
 * контент фестиваля.
 *
 * Сюда НЕ добавляются и имена реальных людей: список не знает, что Тесла
 * можно, а Сталин нельзя, и любой список имён на живом фестивале устареет
 * за день. Решает классификатор (real_people / politics).
 */
import type { ModerationCategory } from './classifier.js';

const RULES: ReadonlyArray<{ re: RegExp; category: ModerationCategory }> = [
  { re: /свастик|swastika|нацистск|nazi\b/i, category: 'hate' },
  { re: /порно|porn|nsfw|обнажённ|обнаженн|\bnude\b|голая\s+(девушк|женщин|дет)/i, category: 'sexual' },
  { re: /мухаммед|мухаммад|muhammad|пророк(а|у)?\s|иисус|jesus\b|христ(а|ос)|будд[ауы]\b|buddha/i, category: 'religion' },
];

/** Сработавшая категория или null. Ничего не спрашивает и не ходит в сеть. */
export function checkStoplist(text: string): ModerationCategory | null {
  for (const r of RULES) if (r.re.test(text)) return r.category;
  return null;
}
