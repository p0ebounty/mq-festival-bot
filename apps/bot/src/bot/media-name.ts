/**
 * Имя файла для загрузки в хранилище kie.ai.
 *
 * Одинаковые имена там ПЕРЕЗАПИСЫВАЮТ старые файлы, а CDN ещё и кэширует
 * (docs/vendor/kie/file-upload-api_upload-file-base-64.md). 05.09 на живом
 * фестивале имя строилось из первых 16 знаков Telegram file_id — а они у
 * всех фото одного бота одинаковые. Три фото трёх разных детей за утро
 * легли под одним адресом, и модель правила чужой снимок: на входе две
 * девушки, на выходе мальчик.
 *
 * Поэтому имя — только из нашего id медиа (uuid), целиком: он уникален и
 * не зависит ни от Telegram, ни от содержимого.
 */
export function kieFileName(prefix: 'tg' | 'mq', mediaId: string): string {
  return `${prefix}-${mediaId}.jpg`;
}
