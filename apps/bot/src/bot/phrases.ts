/**
 * Живые реплики бота. Разнообразие важно: одна и та же фраза на каждое
 * сообщение быстро превращает бота в автоответчик.
 *
 * Выбор детерминированный по счётчику, а не случайный, — чтобы подряд
 * не выпадала одна и та же строка.
 */
const THINKING = [
  'Думаю…',
  'Секунду, соображаю…',
  'Так, прикидываю…',
  'Минутку, обмозгую…',
  'Ага, понял, думаю…',
  'Сейчас разберусь…',
  'Кручу мысль…',
  'Дай подумать…',
];

// Сообщение принято, но ждёт своей очереди — обещаем вернуться, а не отшиваем.
const QUEUED = [
  'Принял, отвечу сразу как доделаю предыдущее 🙂',
  'Записал! Доделаю одно дело — и сразу к этому.',
  'Ок, это следующим. У меня всё-таки не пять рук 🙂',
  'Понял, беру в работу после текущего.',
];

/**
 * Сколько дел впереди. Правило 20-bot-agent обещает участнику **честное**
 * «ты в очереди, №N»: без числа человек не понимает, ждать ему секунду
 * или минуту, и пишет повторно — то есть удлиняет ту самую очередь.
 */
function ahead(n: number): string {
  if (n <= 1) return '';
  return ` Передо мной ещё ${n} ${n < 5 ? 'твоих дела' : 'твоих дел'}.`;
}

