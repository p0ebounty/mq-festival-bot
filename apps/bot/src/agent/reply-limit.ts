/**
 * Ограничитель длины ответа — последний заслон перед отправкой в чат.
 *
 * Промпт это ПРОСЬБА к модели, и её можно переспорить: «ну пожалуйста»,
 * «мне для школы», «ты же можешь». Ограничитель стоит на выходе и не
 * разговаривает с участником вовсе: он смотрит на уже написанный ответ и
 * решает, отправлять ли его. Уговорить его нельзя, потому что он ничего
 * не слушает.
 *
 * Живой случай 27.08 (K1tana, 44 минуты): бот написал участнице
 * Python-скрипт со своей же логикой диспетчеризации, vite-проект на 7722
 * знака и два сценария «Рика и Морти». Один человек сжёг 45% всех входных
 * токенов стенда. Разрешала это строка промпта «если человек просто
 * болтает — поболтай».
 *
 * Порог взят из данных прода, а не из головы. Все ответы трёх нормальных
 * участников за всё время работы: максимум 417 знаков. Все четыре
 * злоупотребления: 2662, 2757, 3068 и 7722. Между облаками пропасть в
 * шесть раз; 1000 стоит посередине с запасом 2,4x над законным максимумом.
 *
 * ⚠️ Первую версию — «считать подряд идущие ходы без вызова инструмента» —
 * пришлось выбросить: на том же диалоге она пропускает ровно два самых
 * дорогих ответа. Модель нервным тиком дёргала get_base_world между
 * абзацами кода, и формально ход выглядел полезным. Длина не обманывается.
 */

/**
 * Инструменты, после которых участнику УЖЕ ушла картинка. Если такой был,
 * заглушка обязана это признать: сказать «я тут только про картинки», когда
 * картинка едет, — это соврать человеку.
 */
export const DRAWING_TOOLS: ReadonlySet<string> = new Set([
  'generate_image',
  'edit_image',
  'get_base_world',
]);

export const MAX_REPLY_CHARS = 1000;

/** Блок кода в ответе бота фестиваля не бывает законным ни при каких условиях. */
const CODE_FENCE = '```';

export interface ReplyCut {
  reason: 'length' | 'code';
  chars: number;
  /** Оригинал уезжает в content_json: без него админка не покажет, что произошло. */
  original: string;
}

export interface CappedReply {
  text: string;
  /** Заполнено, только если ответ подменён. */
  cut?: ReplyCut;
}

const OFF_TOPIC = 'Это не ко мне — я тут картинки рисую. Давай нарисуем что-нибудь?';
const DRAWING = 'Делаю, скоро покажу.';

/**
 * Проверяет готовый ответ агента. Ничего не накапливает между ходами:
 * состояния нет, смотрим одно сообщение.
 *
 * @param drawing была ли в этом ходе удачная выдача картинки
 */
export function capReply(text: string, opts: { drawing: boolean }): CappedReply {
  const reason: ReplyCut['reason'] | null =
    text.includes(CODE_FENCE) ? 'code'
    : text.length > MAX_REPLY_CHARS ? 'length'
    : null;

  if (reason === null) return { text };

  return {
    text: opts.drawing ? DRAWING : OFF_TOPIC,
    cut: { reason, chars: text.length, original: text },
  };
}
