import { z } from 'zod';
import { and, eq, sql } from 'drizzle-orm';
import type { AgentTool } from '@mq/core';
import { baseWorlds } from '@mq/db/schema';
import type { AppContext } from '../../context.js';

/**
 * Выдать задание: картинку и конкретную цель, что из неё получить.
 *
 * Отличие от `get_base_world` — в цели. Мир это свобода («меняй как
 * хочешь»), задание это заданный результат («поставь на арену болид»).
 * Оба лежат в одном пуле картинок и различаются полем kind, но выдаются
 * разными инструментами: намерения участника разные, а инструмент с
 * флагом-переключателем — ровно то, от чего ушли в ADR 0010.
 *
 * Одна картинка — одно задание — один промпт на изменение. Ни шагов, ни
 * проверки выполнения, ни времени на выполнение: работы смотрят люди
 * (ADR 0013).
 */
export function makeGetTaskTool(app: AppContext): AgentTool<Record<string, never>> {
  return {
    name: 'get_task',
    description:
      'Выдать участнику задание — готовую картинку и цель, что из неё нужно получить. ' +
      'Мгновенно и БЕСПЛАТНО, токен не списывается. ' +
      'Вызывай, когда участник просит задание, спрашивает «а что делать», «дай что-нибудь ' +
      'посложнее», хочет проверить себя или не знает, с чего начать. Просит «дай мир», ' +
      '«что есть готового», хочет поиграть без своего фото — это тоже сюда: свободных ' +
      'миров нет, стартовая картинка на фестивале — это задание. ' +
      'Задание не описывают словами — его выдают: перечислить, какие бывают задания, и не ' +
      'дать ни одного значит оставить человека ни с чем. ' +
      'Инструмент сам отправит картинку вместе с текстом задания. ' +
      'Просит другое задание — выдавай другое, не уговаривая: их много, и застревать ' +
      'на одном незачем. Отказывать в смене задания нельзя. ' +
      'НЕ вызывай, если участник просит изменить картинку, которая у него уже есть, — ' +
      'для этого есть edit_image.',
    input: z.object({}),
    parameters: { type: 'object', properties: {}, additionalProperties: false },

    async run(_input, ctx) {
      const [task] = await app.db.select().from(baseWorlds)
        .where(and(eq(baseWorlds.isActive, true), eq(baseWorlds.kind, 'task')))
        // Реже выданные вперёд, дальше случайно: у соседей по стенду должны
        // быть разные задания, иначе сравнивать работы неинтересно.
        .orderBy(baseWorlds.timesIssued, sql`random()`)
        .limit(1);

      if (!task) {
        return {
          ok: false,
          summary: 'Заданий в пуле нет.',
          note: 'Предложи участнику свободный мир через get_base_world или обычную генерацию.',
          error: 'no_tasks',
        };
      }

      await app.db.update(baseWorlds)
        .set({ timesIssued: sql`${baseWorlds.timesIssued} + 1` })
        .where(eq(baseWorlds.id, task.id));
      await app.tasks.setCurrent(ctx.userId, task.id);

      // Текст задания уходит подписью к картинке, а не отдельной репликой:
      // участник должен видеть цель и исходник одновременно.
      const caption = task.taskText ?? 'Измени эту картинку одной фразой.';
      const sent = await app.sendMedia?.(ctx.chatId, task.mediaId, caption);
      if (!sent) {
        return { ok: false, summary: 'Картинку задания отправить не вышло. Попробуй ещё раз.', error: 'send_failed' };
      }
      // Картинка уже ушла участнику, а текст агента по умолчанию
      // вписывается в заглушку «Думаю…» — сообщение, отправленное ДО неё.
      // Получалось «задание под картинкой», написанное над картинкой.
      // Признак переводит ответ в новое сообщение, ниже картинки.
      ctx.notePlaceholderSent?.();
      ctx.log.info({ taskId: task.id, title: task.title }, 'выдано задание');

      return {
        ok: true,
        summary: `Участнику выдано задание: «${caption}». Картинка уже ушла ему отдельным сообщением.`,
        note:
          'Картинка с текстом задания уже отправлена отдельным сообщением. ' +
          'Не пересказывай задание и НЕ пиши «задание под картинкой» или «выше»: ' +
          'сообщения могут прийти в другом порядке, и участник не поймёт, о чём речь. ' +
          'Скажи одной живой фразой, что дальше: пусть напишет своими словами, что изменить. ' +
          'Правильного ответа не подсказывай и не называй — догадаться должен он сам. ' +
          'Менять картинку будешь через edit_image, она появится в списке картинок диалога.',
        // Внутреннее название задания содержит ответ («гонец → дрон»),
        // поэтому наружу отдаётся только текст задания.
        data: { task: caption },
      };
    },
  };
}
