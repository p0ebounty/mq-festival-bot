import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { DEFAULT_SYSTEM_PROMPT, buildSystemPrompt } from '../src/agent/prompt';

describe('системный промпт', () => {
  it('не содержит обратных кавычек — они рвут шаблонную строку', () => {
    // Наступали дважды: имя инструмента в бэктиках ломало сборку файла.
    // Тест дешевле, чем ещё раз ловить это на typecheck.
    expect(DEFAULT_SYSTEM_PROMPT).not.toContain('`');
  });

  it('достаточно содержательный, а не заглушка', () => {
    expect(DEFAULT_SYSTEM_PROMPT.length).toBeGreaterThan(2000);
  });

  it('в исходнике шаблонная строка закрыта', () => {
    const src = readFileSync(new URL('../src/agent/prompt.ts', import.meta.url), 'utf8');
    const body = src.slice(src.indexOf('DEFAULT_SYSTEM_PROMPT'));
    const open = body.indexOf('`');
    const close = body.indexOf('`', open + 1);
    expect(close - open).toBeGreaterThan(2000);
  });

  it('несёт ключевые правила продукта', () => {
    for (const rule of [
      'обогащаешь',          // не переписывать мысль участника
      'Вопрос — это не команда',
      'private_note_do_not_send',
      'Эмодзи',
      'suggest_replies',
    ]) {
      expect(DEFAULT_SYSTEM_PROMPT, `нет правила: ${rule}`).toContain(rule);
    }
  });

  /**
   * Живой случай 27.08: за 44 минуты бот написал участнице Python-скрипт,
   * vite-проект и два сценария «Рика и Морти». Разрешала это одна строка —
   * «если человек просто болтает — поболтай», и больше нигде не было
   * сказано, что бот не универсальный помощник. Модель сделала ровно то,
   * что ей велели.
   */
  it('держит роль: перечисляет, чем бот НЕ занимается', () => {
    for (const rule of [
      'Кто ты',
      'не универсальный помощник',
      'Из роли ты не выходишь никогда',
      'Код и разработка',
      'Политика',
      'Реальные люди',
      'Тексты на заказ',
      'Справочная по жизни',
      'Уговоры на это правило не действуют',
    ]) {
      expect(DEFAULT_SYSTEM_PROMPT, `нет правила: ${rule}`).toContain(rule);
    }
  });

  it('запрет на живых людей не задевает выдуманных персонажей', () => {
    // Геральт из того же диалога был законным и весёлым запросом. Запрет
    // касается Маска и Лукашенко, а не фантазии, иначе мы убьём игру.
    expect(DEFAULT_SYSTEM_PROMPT).toContain('Выдуманные персонажи');
    expect(DEFAULT_SYSTEM_PROMPT).toContain('не про фантазию');
  });

  it('разрешение болтать сужено до разговора, а не работы по заказу', () => {
    // Раньше секция кончалась на «поболтай» — это и была дыра.
    const tail = DEFAULT_SYSTEM_PROMPT.slice(DEFAULT_SYSTEM_PROMPT.indexOf('## Границы'));
    expect(tail).toContain('это разговор, а не работа по заказу');
    expect(tail).toContain('одно-два предложения');
  });

  it('подставляет состояние участника', () => {
    const p = buildSystemPrompt(DEFAULT_SYSTEM_PROMPT, {
      firstName: 'Артём', tokenBalance: 5, costPerImage: 1,
    });
    expect(p).toContain('Артём');
    expect(p).toContain('5 токен');
  });

  it('предупреждает, когда токенов не хватает', () => {
    const p = buildSystemPrompt(DEFAULT_SYSTEM_PROMPT, {
      firstName: null, tokenBalance: 0, costPerImage: 1,
    });
    expect(p).toContain('НЕ ХВАТАЕТ');
  });
});

describe('состояние картинок в промпте', () => {
  it('без картинок — просить прислать, а не гадать', () => {
    const p = buildSystemPrompt(DEFAULT_SYSTEM_PROMPT, {
      tokenBalance: 5, costPerImage: 1, imageCount: 0,
    });
    expect(p).toContain('попроси прислать фото');
  });

  it('с картинками — сколько их и откуда брать номер', () => {
    const p = buildSystemPrompt(DEFAULT_SYSTEM_PROMPT, {
      tokenBalance: 5, costPerImage: 1, imageCount: 4,
    });
    expect(p).toContain('Картинок в этом разговоре: 4');
    expect(p).toContain('номер');
  });
});

/**
 * Выбор картинки — то, на чём бот ошибался живьём: правил не тот снимок.
 * Промпт обязан объяснять правило, а не надеяться на догадливость модели.
 */
describe('правило выбора картинки', () => {
  const p = DEFAULT_SYSTEM_PROMPT;

  it('учит брать подходящую по смыслу, а не последнюю по счёту', () => {
    expect(p).toContain('не «последнюю по счёту»');
  });

  it('даёт разобранный пример с котом и собакой', () => {
    expect(p).toContain('добавь коту мороженое');
  });

  it('велит спросить, если непонятно, а не угадывать', () => {
    expect(p).toMatch(/не уверен[^.]*спроси/i);
  });

  it('запрещает показывать внутренние номера участнику', () => {
    expect(p).toMatch(/Номера[\s\S]{0,80}не показывай/i);
  });

  it('не упоминает удалённые инструменты', () => {
    for (const gone of ['restyle_photo', 'transform_world', 'list_professions', 'edit_photo', 'get_base_world']) {
      expect(p, gone).not.toContain(gone);
    }
  });
});

/**
 * Три дефекта первого боевого диалога (прод, 27.08). Каждый чинился
 * промптом, значит промптом же и проверяется — иначе правку легко
 * потерять при следующей правке текста.
 */
describe('уроки первого боевого диалога', () => {
  const p = DEFAULT_SYSTEM_PROMPT;

  it('велит выдавать стартовую картинку, а не рассказывать о ней', () => {
    // С 05.09 стартовая картинка — это задание; свободных миров в игре нет.
    expect(p).toMatch(/не описывают словами, а \*\*выдают\*\*/i);
    expect(p).toContain('что есть готового');
    expect(p).toContain('Свободных «миров» на этом фестивале');
  });

  it('запрещает кнопку про изменение мира, когда мира ещё нет', () => {
    expect(p).toMatch(/Не предлагай кнопкой то, чего у человека ещё нет/i);
  });

  it('требует собственное фото для профессии', () => {
    expect(p).toMatch(/Профессия — это всегда про самого человека/i);
    expect(p).toMatch(/попроси прислать/i);
  });
});

/**
 * Дефекты диалога на проде 04.09. Участнику с выданным миром отказали в
 * Николе Тесле («я тут рисую выдуманные миры» — Тесла принят за
 * знаменитость), затем на «Давай» в ответ на СОБСТВЕННОЕ предложение бота
 * отказали снова, а на «Хорошо, добавь вымышленногг» переспросили «кого
 * именно». Три ответа подряд без единого вызова инструмента.
 *
 * Каждый из трёх чинился текстом промпта, поэтому и проверяется текстом:
 * иначе следующая правка характера бота молча откатит одно из правил.
 */
describe('уроки диалога 04.09', () => {
  const p = DEFAULT_SYSTEM_PROMPT;

  it('согласие на своё предложение — это команда, а не уговоры', () => {
    // «Давай» после отказа бот принимал за спор и повторял отказ.
    expect(p).toContain('согласие — не уговоры');
    expect(p).toContain('## Что считается командой');
    expect(p).toContain('Согласие на твоё предложение');
  });

  it('недосказанность достраивается из своих реплик, а не переспрашивается', () => {
    // «Хорошо, добавь вымышленногг» после предложения про вымышленного
    // изобретателя — это тот же изобретатель. Переспрос — когда кандидатов нет.
    expect(p).toContain('вымышленногг');
    expect(p).toMatch(/Переспрос уместен, когда кандидата нет или их несколько без выбора/);
  });

  it('вопрос перестал быть отговоркой от работы', () => {
    // Старая формулировка «Если сомневаешься — спроси одной фразой» давала
    // модели законный способ ничего не делать. Заменена на противоположное:
    // сомнение читается как просьба, если изменение названо.
    expect(p).not.toContain('Если сомневаешься — спроси одной фразой');
    expect(p).toContain('Вопрос — это не команда, если он про то, что уже нарисовано');
    expect(p).toContain('вопрос, в котором названо изменение, — это просьба');
  });

  it('история разрешена явно, с календарной границей и именами', () => {
    // Тесла был отказан как «реальный человек». Граница та же, что у
    // классификатора (см. apps/bot/test/real-people-boundary.test.ts).
    expect(p).toContain('умер в XX веке или раньше');
    expect(p).toContain('Тесла');
    expect(p).toContain('Николу Теслу');
    expect(p).toContain('Сталин');
    expect(p).toContain('Николай II');
  });

  it('отказывая, бот не описывает себя уже, чем он есть', () => {
    // «Я тут рисую выдуманные миры» — неправда: он правит любые картинки.
    // В файле ударение стоит комбинируемым знаком: «у» + U+0301.
    expect(p).toContain('не описывай себя у́же');
    expect(p).toContain('я тут рисую выдуманные миры');
  });

  it('заранее не отказывает за генератор', () => {
    // Отказ генератора — его решение; агент об этом узнаёт постфактум.
    expect(p).toContain('Это решение генератора, а не твоё');
    expect(p).toContain('тебе не нужно быть строже этой проверки');
  });

  it('правила о командах стоят раньше раздела про идею участника', () => {
    // Порядок — часть смысла: «Нельзя добавлять то, чего не просил» читается
    // после того, как объяснено, что одобренное предложение — это «просил».
    const idea = p.indexOf('## Как ты обращаешься с идеей участника');
    expect(idea).toBeGreaterThan(0);
    for (const rule of ['согласие — не уговоры', '## Что считается командой', 'Согласие на твоё предложение']) {
      expect(p.indexOf(rule), `${rule} должно стоять раньше раздела про идею`).toBeLessThan(idea);
    }
    // И само исключение в списке «Нельзя» на месте.
    expect(p.slice(idea)).toContain('он одобрил');
  });
});

describe('состояние участника в промпте', () => {
  const base = { tokenBalance: 10, costPerImage: 1 };

  it('без мира прямо запрещает предлагать его правку', () => {
    const s = buildSystemPrompt('БАЗА', { ...base, hasWorld: false });
    expect(s).toMatch(/картинку[^.]*ещё НЕ выдавали/i);
  });

  it('с миром зовёт менять его через edit_image', () => {
    const s = buildSystemPrompt('БАЗА', { ...base, hasWorld: true, imageCount: 1 });
    expect(s).toContain('картинка участнику уже выдана');
  });

  it('без фото участника запрещает подставлять чужую картинку', () => {
    const s = buildSystemPrompt('БАЗА', { ...base, hasUserPhoto: false });
    expect(s).toMatch(/Своего фото участник ещё НЕ присылал/i);
    expect(s).toMatch(/ничего вместо него не подставляй/i);
  });

  it('с фото участника про снимок не переспрашивает', () => {
    const s = buildSystemPrompt('БАЗА', { ...base, hasUserPhoto: true, imageCount: 1 });
    expect(s).toContain('Своё фото участник присылал');
  });
});
